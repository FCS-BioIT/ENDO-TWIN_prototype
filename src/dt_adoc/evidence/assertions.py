"""Relation-level evidence provenance for the literature superset model.

`edge_evidence.tsv` (generated by
`dt_adoc.model.superset_family.build_edge_evidence`) is keyed one row per
`edge_id`, and every consumer -- `runtime.py`, `runner.py`, `dynamics.py`,
`render_dynamics.py`, `config/visualization.yaml`, and several tests --
depends on that shape and on its exact column set. It therefore structurally
cannot hold more than one evidence assertion per edge without breaking those
consumers, yet the same edge is frequently supported by several distinct
papers, in-house observations, or experimental systems that must not be
collapsed into a single row.

This module builds and validates the 1:N companion table that resolves that
tension without touching `edge_evidence.tsv`:

`models/superset/adoc-literature-superset-v0.3.0/edge_evidence_assertions.tsv`

keyed by `edge_id` as a foreign key into `edge_evidence.tsv`, many rows per
edge allowed. It is the single canonical relation-level provenance store --
no other file should hold this information.

`migrate_edge_evidence` is a conservative, mechanical migration of the 93
existing executable edges. It invents no biology: every field that cannot be
read directly off `edge_evidence.tsv`, `context/evidence-register.tsv`, or
`context/literature/references.tsv` is left at an explicit "not yet known"
placeholder (`unknown` / `not_assessed` / `not_yet_curated` / empty) rather
than a guessed value. The one field that is *computed* rather than copied is
`species_transfer_required`, and only mechanically: it is set to `"true"`
when the copied `species_evidence` text names a non-human organism, purely so
that kind of evidence can never silently read as human evidence while
uncurated. That is a visibility flag, not a scientific judgement about
whether the transfer is valid -- the judgement itself is left to a human
curator via `species_transfer_rationale` and `curation_status`.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from dt_adoc.evidence.citation_adjudications import (
    check_applicability,
    load_citation_adjudications,
    partition,
)
from dt_adoc.model.catalog import load_tsv
from dt_adoc.reporting.tables import write_tsv


def repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


EDGE_EVIDENCE_PATH = "models/superset/adoc-literature-superset-v0.3.0/edge_evidence.tsv"
ASSERTIONS_PATH = (
    "models/superset/adoc-literature-superset-v0.3.0/edge_evidence_assertions.tsv"
)
EVIDENCE_REGISTER_PATH = "context/evidence-register.tsv"
CITATION_ADJUDICATIONS_PATH = Path("config/edge_citation_adjudications.tsv")
REFERENCES_PATH = "context/literature/references.tsv"

ASSERTION_COLUMNS = (
    "assertion_id",
    "edge_id",
    "evidence_origin",
    "reference_id",
    "source_observation_id",
    "species_evidence",
    "target_species",
    "species_transfer_required",
    "species_transfer_rationale",
    "compartment",
    "experimental_system",
    "directness",
    "support_type",
    "evidence_grade",
    "direction_supported",
    "context_dependence",
    "implementation_class",
    "curation_status",
    "support_rationale",
)

EVIDENCE_ORIGIN_VALUES = (
    "bibliographic",
    "in_house_experiment",
    "database",
    "expert_assumption",
    "model_structure",
)
DIRECTNESS_VALUES = ("direct", "indirect", "composite_or_inferred", "unknown")
SUPPORT_TYPE_VALUES = (
    "perturbational",
    "genetic",
    "pharmacological",
    "biochemical",
    "functional",
    "associative",
    "descriptive",
    "unknown",
)
EVIDENCE_GRADE_VALUES = ("A", "B", "C", "D", "E", "not_yet_graded")
DIRECTION_SUPPORTED_VALUES = ("supported", "not_assessed", "contradicted")
CURATION_STATUS_VALUES = ("not_yet_curated", "curated", "disputed")
IMPLEMENTATION_CLASS_VALUES = (
    "executable_core",
    "uncertain_rule_variant",
    "catalog_only",
    "external_boundary",
    "phenotype_or_logical_aggregate",
    "physiboss2_coupled_model_later",
    "unsupported_candidate",
    "deprecated",
)

#: The model's declared target organism. This is a modelling fact stated by
#: the family (the superset is built for the human ADOC), not an inference.
TARGET_SPECIES = "human"

_NON_HUMAN_RE = re.compile(
    r"\b(mouse|mice|murine|rat|rats|baboon|non-human)\b", re.IGNORECASE
)


def _species_transfer_required(species_evidence: str) -> str:
    """Mechanical, non-biological derivation from the already-copied
    ``species_evidence`` text: does it name a non-human organism? This never
    judges whether a cross-species transfer is scientifically sound -- it
    only prevents non-human evidence from defaulting to an unlabeled/unknown
    state that would let it silently pass as human evidence."""
    if _NON_HUMAN_RE.search(species_evidence or ""):
        return "true"
    return "unknown"


@dataclass
class AssertionReport:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    checks: list[str] = field(default_factory=list)
    summary: dict[str, object] = field(default_factory=dict)

    @property
    def status(self) -> str:
        return "assertions_intact" if not self.errors else "assertion_defects"

    def payload(self) -> dict[str, object]:
        return {
            "status": self.status,
            "errors": self.errors,
            "warnings": self.warnings,
            "checks": self.checks,
            "summary": self.summary,
        }


def _paths(root: Path | None) -> dict[str, Path]:
    active_root = root or repo_root()
    return {
        "edge_evidence": active_root / EDGE_EVIDENCE_PATH,
        "assertions": active_root / ASSERTIONS_PATH,
        "register": active_root / EVIDENCE_REGISTER_PATH,
        "references": active_root / REFERENCES_PATH,
        "citation_adjudications": active_root / CITATION_ADJUDICATIONS_PATH,
    }


def load_assertions(root: Path | None = None) -> list[dict[str, str]]:
    """Load `edge_evidence_assertions.tsv`. Returns [] if it has not been
    generated yet (e.g. a fresh checkout before `migrate_edge_evidence`)."""
    path = _paths(root)["assertions"]
    if not path.exists():
        return []
    return load_tsv(path)


#: Columns a human curator owns. ``migrate_edge_evidence`` regenerates every
#: other column from the source tables, but must never overwrite these -- they
#: hold the claim-level judgement that reading a paper produces, and there is
#: nowhere else in the repository to put it.
CURATOR_OWNED_COLUMNS = (
    "species_evidence",
    "species_transfer_rationale",
    "compartment",
    "experimental_system",
    "directness",
    "support_type",
    "evidence_grade",
    "direction_supported",
    "context_dependence",
    "implementation_class",
    "curation_status",
    "support_rationale",
)

#: Values a freshly generated row carries. A curator-owned column still holding
#: its placeholder has not been curated, so the regenerated value wins; anything
#: else is a human judgement and is preserved.
_PLACEHOLDERS = {
    "directness": "unknown",
    "support_type": "unknown",
    "evidence_grade": "not_yet_graded",
    "direction_supported": "not_assessed",
    "implementation_class": "executable_core",
    "curation_status": "not_yet_curated",
}


def _merge_curation(
    generated: list[dict[str, str]], existing: list[dict[str, str]]
) -> list[dict[str, str]]:
    """Carry curator-owned fields from ``existing`` onto freshly generated rows.

    Keyed on ``assertion_id``. A curated value survives regeneration; a value
    still equal to its placeholder does not, so a corrected source table can
    still propagate. Rows whose assertion_id has disappeared are dropped -- the
    relation they described no longer exists.
    """
    previous = {row["assertion_id"]: row for row in existing if row.get("assertion_id")}
    for row in generated:
        prior = previous.get(row["assertion_id"])
        if prior is None:
            continue
        for column in CURATOR_OWNED_COLUMNS:
            value = prior.get(column, "").strip()
            if value and value != _PLACEHOLDERS.get(column, ""):
                row[column] = prior[column]
    return generated


def _base_row(edge_id: str) -> dict[str, str]:
    return {
        "assertion_id": "",
        "edge_id": edge_id,
        "evidence_origin": "",
        "reference_id": "",
        "source_observation_id": "",
        "species_evidence": "",
        "target_species": TARGET_SPECIES,
        "species_transfer_required": "unknown",
        "species_transfer_rationale": "",
        "compartment": "",
        "experimental_system": "",
        "directness": "unknown",
        "support_type": "unknown",
        "evidence_grade": "not_yet_graded",
        "direction_supported": "not_assessed",
        "context_dependence": "",
        "implementation_class": "executable_core",
        "curation_status": "not_yet_curated",
        "support_rationale": "",
    }


def migrate_edge_evidence(root: Path | None = None) -> list[dict[str, str]]:
    """Deterministically rebuild `edge_evidence_assertions.tsv` from the
    current `edge_evidence.tsv`, `context/evidence-register.tsv`, and
    `context/literature/references.tsv`, then merge any existing curator-owned
    fields back on top. Idempotent: given unchanged source files, running this
    twice writes byte-identical output.

    Assertion ids are CONTENT-ADDRESSED (``ASRT-<edge>-<reference>``), not
    positional. They used to be ``ASRT-<edge>-<n>`` where n indexed the evidence
    register's semicolon-separated location list, so inserting a reference into
    that list renumbered every id after it -- and because the merge below keys on
    assertion_id, a curator's judgement about one paper would silently migrate
    onto a different one. Correcting a defective citation requires editing
    exactly such a list, so positional ids made the repair unsafe.

    The merge is not optional. Curation is written into this file and nowhere
    else, the unit suite invokes this function against the real repository
    root, and a plain rebuild silently discarded every claim-level judgement it
    found -- so a rebuild would make curating a paper impossible.

    Adds no biological relation and changes no existing model content --
    `edge_evidence.tsv` is only read, never written, by this function.
    """
    paths = _paths(root)
    edge_rows = load_tsv(paths["edge_evidence"])
    register = {row["evidence_id"]: row for row in load_tsv(paths["register"])}
    references = {row["ref_id"]: row for row in load_tsv(paths["references"])}

    def topic_references(evidence_id: str) -> list[str]:
        return [
            token.strip()
            for token in register.get(evidence_id, {}).get("location", "").split(";")
            if token.strip().startswith("REF-")
        ]

    # The register keys its bibliography by topic and this function fans a
    # topic's whole list onto every citing edge. Directives supply the missing
    # per-relation granularity; see dt_adoc.evidence.citation_adjudications.
    baseline = {
        edge["edge_id"]: topic_references(edge["evidence_id"].strip())
        for edge in edge_rows
    }
    adjudications = load_citation_adjudications(
        paths["citation_adjudications"],
        [edge["edge_id"] for edge in edge_rows],
        list(references),
    )
    check_applicability(adjudications, baseline)
    retracted, attachments = partition(adjudications)

    rows: list[dict[str, str]] = []
    for edge in edge_rows:
        edge_id = edge["edge_id"]
        evidence_id = edge["evidence_id"].strip()
        register_row = register.get(evidence_id)

        if evidence_id.startswith("SOFIA-"):
            row = _base_row(edge_id)
            system = (register_row or {}).get("system", "")
            row["assertion_id"] = f"ASRT-{edge_id}-{evidence_id}"
            row["evidence_origin"] = "in_house_experiment"
            row["source_observation_id"] = evidence_id
            row["species_evidence"] = system
            row["compartment"] = system
            row["experimental_system"] = system
            row["species_transfer_required"] = _species_transfer_required(system)
            rows.append(row)
        elif evidence_id.startswith("LIT-"):
            ref_ids = list(baseline[edge_id])
            ref_ids.extend(
                ref for ref in attachments.get(edge_id, ()) if ref not in ref_ids
            )
            for ref_id in ref_ids:
                if (edge_id, ref_id) in retracted:
                    continue
                row = _base_row(edge_id)
                ref_row = references.get(ref_id, {})
                row["assertion_id"] = f"ASRT-{edge_id}-{ref_id}"
                row["evidence_origin"] = "bibliographic"
                row["reference_id"] = ref_id
                species_evidence = ref_row.get("species", "")
                row["species_evidence"] = species_evidence
                row["compartment"] = ref_row.get("compartment", "")
                row["experimental_system"] = ref_row.get("study_type", "")
                row["species_transfer_required"] = _species_transfer_required(
                    species_evidence
                )
                rows.append(row)
        else:
            # Neither a SOFIA nor a LIT id: record it rather than drop or
            # guess at it. None of the 93 current executable edges hit this
            # branch, but a future edge added under an unrecognised evidence
            # family must still get exactly one visibly-uncurated row.
            row = _base_row(edge_id)
            row["assertion_id"] = f"ASRT-{edge_id}-UNSOURCED"
            row["evidence_origin"] = "database"
            rows.append(row)

    rows = _merge_curation(rows, load_assertions(root))
    write_tsv(paths["assertions"], rows)
    return rows


def validate_assertions(root: Path | None = None) -> AssertionReport:
    """Validate `edge_evidence_assertions.tsv` against `edge_evidence.tsv`,
    the evidence register, and the bibliography. Mirrors the report shape of
    `dt_adoc.evidence.citations.CitationReport` (errors/warnings/checks) plus
    a `summary` of curation counts."""
    paths = _paths(root)
    report = AssertionReport()

    edge_rows = load_tsv(paths["edge_evidence"])
    edge_ids = {row["edge_id"] for row in edge_rows}
    assertions = load_assertions(root)

    if not assertions:
        report.errors.append(
            f"no assertions found at {paths['assertions']}; "
            "run migrate_edge_evidence() first"
        )
        return report

    references = {row["ref_id"] for row in load_tsv(paths["references"])}
    observations = {row["evidence_id"] for row in load_tsv(paths["register"])}

    assertions_by_edge: dict[str, list[dict[str, str]]] = {}
    seen_assertion_ids: dict[str, int] = {}
    for row in assertions:
        assertions_by_edge.setdefault(row["edge_id"], []).append(row)
        aid = row.get("assertion_id", "").strip()
        if not aid:
            report.errors.append(
                f"assertion for edge {row['edge_id']} has no assertion_id"
            )
        else:
            seen_assertion_ids[aid] = seen_assertion_ids.get(aid, 0) + 1
    report.checks.append("edge_ids_have_assertions")

    for edge_id in sorted(edge_ids):
        if not assertions_by_edge.get(edge_id):
            report.errors.append(f"edge {edge_id} has no evidence assertion")

    for aid, count in seen_assertion_ids.items():
        if count > 1:
            report.errors.append(f"duplicate assertion_id {aid!r} ({count} rows)")
    report.checks.append("assertion_id_uniqueness")

    curated_count = 0
    not_yet_curated_count = 0
    disputed_count = 0
    origin_counts: dict[str, int] = {}
    direction_counts: dict[str, int] = {}
    transfer_required_true = 0

    for row in assertions:
        edge_id = row["edge_id"]
        if edge_id not in edge_ids:
            report.errors.append(
                f"assertion {row.get('assertion_id')} references unknown edge_id {edge_id!r}"
            )

        origin = row.get("evidence_origin", "")
        origin_counts[origin] = origin_counts.get(origin, 0) + 1
        if origin not in EVIDENCE_ORIGIN_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid evidence_origin {origin!r}"
            )

        if origin == "bibliographic":
            ref_id = row.get("reference_id", "").strip()
            if not ref_id:
                report.errors.append(
                    f"bibliographic assertion {row.get('assertion_id')} has empty reference_id"
                )
            elif ref_id not in references:
                report.errors.append(
                    f"assertion {row.get('assertion_id')} cites unknown reference {ref_id!r}"
                )

        if origin == "in_house_experiment":
            obs_id = row.get("source_observation_id", "").strip()
            if not obs_id:
                report.errors.append(
                    f"in_house_experiment assertion {row.get('assertion_id')} has empty "
                    "source_observation_id"
                )
            elif obs_id not in observations:
                report.errors.append(
                    f"assertion {row.get('assertion_id')} cites unknown observation "
                    f"{obs_id!r}"
                )

        species_evidence = row.get("species_evidence", "")
        target_species = row.get("target_species", "")
        transfer_required = row.get("species_transfer_required", "")
        curation_status = row.get("curation_status", "")

        if transfer_required == "true":
            transfer_required_true += 1

        if (
            target_species == "human"
            and _NON_HUMAN_RE.search(species_evidence or "")
            and transfer_required != "true"
        ):
            report.errors.append(
                f"assertion {row.get('assertion_id')} has non-human species_evidence "
                f"{species_evidence!r} with target_species=human but "
                f"species_transfer_required={transfer_required!r} (must be 'true')"
            )

        if (
            transfer_required == "true"
            and curation_status != "not_yet_curated"
            and not row.get("species_transfer_rationale", "").strip()
        ):
            report.errors.append(
                f"assertion {row.get('assertion_id')} has species_transfer_required=true "
                "and is curated but species_transfer_rationale is empty"
            )

        if curation_status == "curated":
            curated_count += 1
            if row.get("directness") == "unknown":
                report.errors.append(
                    f"assertion {row.get('assertion_id')} is curated but directness=unknown"
                )
            if row.get("support_type") == "unknown":
                report.errors.append(
                    f"assertion {row.get('assertion_id')} is curated but support_type=unknown"
                )
        elif curation_status == "not_yet_curated":
            not_yet_curated_count += 1
        elif curation_status == "disputed":
            disputed_count += 1
        else:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid curation_status "
                f"{curation_status!r}"
            )

        direction = row.get("direction_supported", "")
        direction_counts[direction] = direction_counts.get(direction, 0) + 1
        if direction not in DIRECTION_SUPPORTED_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid direction_supported "
                f"{direction!r}"
            )

        if row.get("directness") not in DIRECTNESS_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid directness "
                f"{row.get('directness')!r}"
            )
        if row.get("support_type") not in SUPPORT_TYPE_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid support_type "
                f"{row.get('support_type')!r}"
            )
        if row.get("evidence_grade") not in EVIDENCE_GRADE_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid evidence_grade "
                f"{row.get('evidence_grade')!r}"
            )
        if row.get("implementation_class") not in IMPLEMENTATION_CLASS_VALUES:
            report.errors.append(
                f"assertion {row.get('assertion_id')} has invalid implementation_class "
                f"{row.get('implementation_class')!r}"
            )

    report.checks.append("evidence_origin_vocabulary")
    report.checks.append("bibliographic_reference_ids_resolve")
    report.checks.append("in_house_observation_ids_resolve")
    report.checks.append("species_transfer_visibility")
    report.checks.append("curation_completeness")
    report.checks.append("controlled_vocabulary_values")

    report.summary = {
        "assertion_count": len(assertions),
        "edge_count": len(edge_ids),
        "edges_with_assertions": len(assertions_by_edge),
        "by_evidence_origin": origin_counts,
        "by_direction_supported": direction_counts,
        "curated_count": curated_count,
        "not_yet_curated_count": not_yet_curated_count,
        "disputed_count": disputed_count,
        "species_transfer_required_true_count": transfer_required_true,
    }
    return report


def main(argv: list[str] | None = None) -> int:
    import argparse
    import json

    parser = argparse.ArgumentParser(
        prog="dt-adoc-evidence-assertions",
        description="Migrate and validate relation-level evidence assertions.",
    )
    parser.add_argument(
        "--skip-migrate",
        action="store_true",
        help="Validate the existing file instead of regenerating it first.",
    )
    args = parser.parse_args(argv)

    if not args.skip_migrate:
        rows = migrate_edge_evidence()
        print(f"wrote {len(rows)} assertions")

    report = validate_assertions()
    print(json.dumps(report.payload(), indent=2))
    return 0 if not report.errors else 1


if __name__ == "__main__":
    raise SystemExit(main())
