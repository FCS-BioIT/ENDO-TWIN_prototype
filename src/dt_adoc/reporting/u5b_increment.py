def build_increment(root: Path) -> dict[str, bytes]:
    """Every file of v0.5.1, as bytes, keyed by path relative to the model dir.

    Pure: reads v0.5.0 and the shared adjudications, writes nothing.
    """
    parent = root / PARENT_DIR
    files: dict[str, bytes] = {
        str(path.relative_to(parent)): path.read_bytes()
        for path in sorted(parent.rglob("*"))
        if path.is_file()
    }
    parent_hashes = {name: _sha256_bytes(data) for name, data in files.items()}

    files["network.bnd"] = _repair_bnd(files["network.bnd"].decode("utf-8")).encode(
        "utf-8"
    )
    files[LOCAL_ADJUDICATIONS] = _tsv_bytes(
        local_adjudication_rows(), ADJUDICATION_COLUMNS, "\n"
    )

    # Reconcile against what is about to be written, in a scratch file, so the
    # retirement is derived by the repository's own parity code, not asserted.
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp)
        (scratch / "network.bnd").write_bytes(files["network.bnd"])
        (scratch / LOCAL_ADJUDICATIONS).write_bytes(files[LOCAL_ADJUDICATIONS])
        topology = reconcile(
            parse_bnd_rules(scratch / "network.bnd"),
            _read_tsv(parent / "edge_evidence.tsv"),
            adjudications_for_increment(root, scratch / LOCAL_ADJUDICATIONS),
        )
    files["topology.tsv"] = _tsv_bytes(topology, TOPOLOGY_COLUMNS, "\r\n")
    files["executable_modules_network.mmd"] = _repair_mermaid(
        files["executable_modules_network.mmd"].decode("utf-8")
    ).encode("utf-8")
    files["executable_model_manifest.tsv"] = _repair_manifest(
        files["executable_model_manifest.tsv"]
    )
    files["README.md"] = README.encode("utf-8")

    new_hashes = {key: _sha256_bytes(files[name]) for name, key in _HASH_KEYS.items()}
    files["provenance.toml"] = _repair_provenance(
        files["provenance.toml"].decode("utf-8"),
        new_hashes,
        parent_hashes,
        _sha256_bytes(files[LOCAL_ADJUDICATIONS]),
    ).encode("utf-8")
    return files


def write_increment(root: Path) -> Path:
    """Write v0.5.1. Refuses to touch anything outside its own directory."""
    destination = root / MODEL_DIR
    if destination.exists():
        shutil.rmtree(destination)
    for name, data in build_increment(root).items():
        path = destination / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return destination


def truth_tables(model_dir: Path) -> tuple[tuple[str, ...], dict[str, int], int]:
    """Every node's composed function over the free variables, as bit columns.

    The free variables are read from the rules (``X = X``), exactly as
    ``dt_adoc.reporting.structure.load_structure`` reads them, and the columns are
    computed by that module's own evaluator.
    """
    rules = parse_bnd_rules(model_dir / "network.bnd")
    free = tuple(n for n in rules if rules[n].strip() == n)
    states = 2 ** len(free)
    mask = (1 << states) - 1
    seeds: dict[str, int] = {}
    for index, node_id in enumerate(free):
        block = 1 << index
        column = 0
        for start in range(block, states, block * 2):
            column |= ((1 << block) - 1) << start
        seeds[node_id] = column
    order = _topological_order(rules, set(free))
    return free, _columns(rules, order, seeds, mask), states


def structural_identity(root: Path) -> dict[str, Any]:
    """The composed-function comparison, and the blast radius, from the rules."""
    parent_free, parent_cols, states = truth_tables(root / PARENT_DIR)
    free, cols, _ = truth_tables(root / MODEL_DIR)
    parent_rules = parse_bnd_rules(root / PARENT_DIR / "network.bnd")
    rules = parse_bnd_rules(root / MODEL_DIR / "network.bnd")
    changed_rules = sorted(n for n in rules if rules[n] != parent_rules.get(n))
    differing = sorted(n for n in cols if cols[n] != parent_cols.get(n))
    readers = sorted(
        n
        for n, logic in rules.items()
        if REPAIRED_NODE in re.findall(r"\b\w+\b", logic)
    )
    return {
        "free_variables_parent": list(parent_free),
        "free_variables": list(free),
        "enumerated_assignments": states,
        "nodes": len(rules),
        "rules_changed": changed_rules,
        "nodes_whose_composed_function_differs": differing,
        "readers_of_repaired_node": readers,
        "adhesion_competence_rule": rules["OUT_MATERNAL_ADHESION_COMPETENCE"],
    }


