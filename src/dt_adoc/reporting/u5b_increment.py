def _repair_provenance(
    parent_text: str,
    new_hashes: dict[str, str],
    parent_hashes: dict[str, str],
    local_adjudications_sha256: str,
) -> str:
    text = parent_text
    # The version-local adjudications are a derivation input of topology.tsv,
    # exactly as the shared file is, so they are hashed beside it under
    # [source_hashes].
    shared = re.compile(
        r'^(topology_adjudications_sha256 = "[0-9a-f]{64}")$', re.MULTILINE
    )
    text, count = shared.subn(
        rf'\g<1>\ntopology_increment_adjudications_sha256 = "{local_adjudications_sha256}"',
        text,
    )
    if count != 1:
        raise ValueError("topology_adjudications_sha256 not found exactly once")
    for old, new in (
        (
            'family_id = "adoc_literature_superset_v050"',
            'family_id = "adoc_literature_superset_v051"',
        ),
        (f'model_version = "{PARENT_VERSION}"', f'model_version = "{MODEL_VERSION}"'),
        ('generated_on = "2026-09-17"', f'generated_on = "{GENERATED_ON}"'),
        (
            'generator_module = "none_copied_from_parent"',
            'generator_module = "dt_adoc.reporting.u5b_increment"',
        ),
    ):
        if text.count(old) != 1:
            raise ValueError(f"provenance header line not found exactly once: {old}")
        text = text.replace(old, new)
    note = re.compile(r'^generator_note = ".*"$', re.MULTILINE)
    text, count = note.subn(
        'generator_note = "Emitted from adoc-literature-superset-v0.5.0 by U5b as '
        "that version plus one repaired rule. dt_adoc.model.superset_family."
        'MODEL_VERSION still targets v0.4.0 and emits neither v0.5 directory."',
        text,
    )
    if count != 1:
        raise ValueError("generator_note not found exactly once")
    parent_prefix = f'"{PARENT_DIR.as_posix()}/'
    if text.count(parent_prefix) != 18:
        raise ValueError("expected 18 [artifacts] paths naming the parent")
    text = text.replace(parent_prefix, f'"{MODEL_DIR.as_posix()}/')
    for key, digest in new_hashes.items():
        line = re.compile(rf'^{key}_sha256 = "[0-9a-f]{{64}}"$', re.MULTILINE)
        text, count = line.subn(f'{key}_sha256 = "{digest}"', text)
        if count != 1:
            raise ValueError(f"{key}_sha256 not found exactly once")
    cut = text.index("\n[scaffold]\n")
    block = _INCREMENT_BLOCK.format(
        parent_dir=PARENT_DIR.as_posix(),
        parent_version=PARENT_VERSION,
        generated_on=GENERATED_ON,
        node=REPAIRED_NODE,
        before=LOGIC_BEFORE,
        after=LOGIC_AFTER,
        changed="\n".join(f'  "{name}",' for name in sorted(CHANGED_FILES)),
        added="\n".join(f'  "{name}",' for name in sorted(ADDED_FILES)),
        parent_provenance=parent_hashes["provenance.toml"],
        parent_bnd=parent_hashes["network.bnd"],
        parent_cfg=parent_hashes["baseline.cfg"],
    )
    return text[:cut] + "\n" + block


