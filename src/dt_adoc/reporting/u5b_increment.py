"""U5b: emit ``adoc-literature-superset-v0.5.1`` from v0.5.0, and prove what moved.

``docs/v05_mechanistic_integration_plan.md`` §17 U5b is the first
mechanism-changing unit of the v0.5 line, and the rule it follows is that an
audited model version is a fixed object: the increment is emitted as a new
directory and v0.5.0 is left exactly as U5 audited it. This module is the one
place that directory comes from, so ``tests/unit/test_v05_u5b_readout_repair.py``
can rebuild it in a scratch tree and require it byte-for-byte.

The increment is one rule:

    OUT_STROMAL_DECIDUALIZED = S_DECIDUALIZED and S_PRL and S_IGFBP1
    OUT_STROMAL_DECIDUALIZED = S_DECIDUALIZED

``S_PRL`` and ``S_IGFBP1`` are calibration readouts, and a reported phenotype
must not use them as causal gates. Their conjuncts are absorbed in every one of
the 2**19 free-variable assignments (``S_PRL = S_IGFBP1 = S_DECIDUALIZED``), so the
composed function of every node is unchanged -- ``structural_identity`` checks
that node by node rather than inferring it from the absorption.

Everything else is copied byte-for-byte except what the rule change or
self-naming forces:

* ``network.bnd`` -- the rule.
* ``topology.tsv`` -- regenerated by ``dt_adoc.model.topology.reconcile``, not
  hand-edited. ``LE079`` and ``LE080`` no longer execute, so they become
  ``retired``: the repository's convention keeps the curated row and its
  evidence as history rather than deleting it.
* ``topology_increment_adjudications.tsv`` -- NEW. ``reconcile`` retires a row only
  against a dated adjudication, and the repository's adjudication file
  (``config/topology_parity_exemptions.tsv``) cannot take the two rows: v0.4.0 and
  v0.5.0 record its sha256 as a source hash, and both still execute those edges,
  where a retirement row would be an error. So the retirement is version-local
  and extends the shared file rather than editing it.
* ``executable_modules_network.mmd`` -- the two arrows that no longer execute.
* ``provenance.toml``, ``README.md``, ``executable_model_manifest.tsv`` --
  self-naming and the ``[increment]`` record, as U1 did for the scaffold.

Deliberately NOT changed, with the reason, so a later reader does not "finish"
the job: ``edge_evidence.tsv`` keeps ``LE079``/``LE080`` as curated history (the
retirement lives in ``topology.tsv``, as ``LE081``'s does); ``complete_edges.tsv``
states its implementation columns against ``implementation_model_version =
adoc-literature-superset-v0.4.0``, where both edges do execute, so it is still
true; ``phenotype_contract.tsv`` and ``node_dictionary.tsv`` describe the
phenotype, not the rule, and neither names the marker gates.
"""

