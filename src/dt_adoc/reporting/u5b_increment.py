def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def _tsv_bytes(
    rows: list[dict[str, str]], columns: tuple[str, ...], lineterminator: str
) -> bytes:
    buffer = io.StringIO(newline="")
    writer = csv.DictWriter(
        buffer,
        fieldnames=list(columns),
        delimiter="\t",
        lineterminator=lineterminator,
    )
    writer.writeheader()
    for row in rows:
        writer.writerow({column: row.get(column, "") for column in columns})
    return buffer.getvalue().encode("utf-8")


def local_adjudication_rows() -> list[dict[str, str]]:
    return [
        {
            "exemption_id": f"INC-U5B-0{index}",
            "source_node": source,
            "target_node": target,
            "category": "stale_topology_row_undocumented_migration",
            "adjudication": "retire_row_preserve_assertions",
            "rationale": _RATIONALE.format(edge_id=edge_id, source=source),
            "action_required": "none",
            "dated": GENERATED_ON,
        }
        for index, (source, target, edge_id) in enumerate(
            sorted(RETIRED_EDGES, key=lambda edge: edge[2]), start=1
        )
    ]


def adjudications_for_increment(
    root: Path, local_path: Path
) -> dict[tuple[str, str], dict[str, str]]:
    """The shared adjudications extended by the version-local ones, never edited."""
    shared = load_adjudications(root / SHARED_ADJUDICATIONS)
    local = load_adjudications(local_path)
    overlap = sorted(set(shared) & set(local))
    if overlap:
        raise ValueError(f"version-local adjudications shadow shared ones: {overlap}")
    return {**shared, **local}


def _repair_bnd(text: str) -> str:
    pattern = re.compile(
        rf"(Node {REPAIRED_NODE} \{{\n  logic = ){re.escape(LOGIC_BEFORE)}(;\n\}})"
    )
    repaired, count = pattern.subn(rf"\g<1>{LOGIC_AFTER}\g<2>", text)
    if count != 1:
        raise ValueError(
            f"{REPAIRED_NODE}'s parent rule not found exactly once ({count})"
        )
    return repaired


def _repair_mermaid(text: str) -> str:
    for source, target, _ in RETIRED_EDGES:
        line = f"  {source} --> {target}\n"
        if text.count(line) != 1:
            raise ValueError(f"arrow {source} --> {target} not found exactly once")
        text = text.replace(line, "")
    return text


