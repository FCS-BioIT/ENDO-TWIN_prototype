def _repair_provenance(
    parent_text: str,
    model_version: str,
    changes: tuple[RuleChange, ...],
    new_hashes: dict[str, str],
    parent_hashes: dict[str, str],
) -> str:
    text = parent_text
    for old, new in (
        (
            'family_id = "adoc_literature_superset_v051"',
            f'family_id = "{_family_key(model_version)}"',
        ),
        (f'model_version = "{PARENT_VERSION}"', f'model_version = "{model_version}"'),
        ('generated_on = "2026-09-23"', f'generated_on = "{GENERATED_ON}"'),
        (
            'generator_module = "dt_adoc.reporting.u5b_increment"',
            'generator_module = "dt_adoc.reporting.v052_increment"',
        ),
    ):
        if text.count(old) != 1:
            raise ValueError(f"provenance header line not found exactly once: {old}")
        text = text.replace(old, new)
    note = re.compile(r'^generator_note = ".*"$', re.MULTILINE)
    text, count = note.subn(
        f'generator_note = "Emitted from {PARENT_VERSION} by '
        "dt_adoc.reporting.v052_increment as that version with absorbed conjuncts "
        "removed. dt_adoc.model.superset_family.MODEL_VERSION still targets v0.4.0 "
        'and emits no v0.5 directory."',
        text,
    )
    if count != 1:
        raise ValueError("generator_note not found exactly once")
    parent_prefix = f'"{PARENT_DIR.as_posix()}/'
    if text.count(parent_prefix) != 18:
        raise ValueError("expected 18 [artifacts] paths naming the parent")
    text = text.replace(parent_prefix, f'"{(SUPERSET_DIR / model_version).as_posix()}/')
    for hash_key, digest in new_hashes.items():
        line = re.compile(rf'^{hash_key}_sha256 = "[0-9a-f]{{64}}"$', re.MULTILINE)
        text, count = line.subn(f'{hash_key}_sha256 = "{digest}"', text)
        if count != 1:
            raise ValueError(f"{hash_key}_sha256 not found exactly once")
    cut = text.index("\n[increment]\n")
    block = _INCREMENT_BLOCK.format(
        parent_dir=PARENT_DIR.as_posix(),
        parent_version=PARENT_VERSION,
        generated_on=GENERATED_ON,
        count=len(changes),
        change_ids=", ".join(f'"{c.change_id}"' for c in changes),
        rule_lines="\n".join(
            f'{c.change_id.lower()}_rule_changed = "{c.node}"\n'
            f'{c.change_id.lower()}_logic_before = "{c.logic_before}"\n'
            f'{c.change_id.lower()}_logic_after = "{c.logic_after}"'
            for c in changes
        ),
        edges=", ".join(f'"{c.edge_id}"' for c in changes),
        changed="\n".join(f'  "{name}",' for name in sorted(CHANGED_FILES)),
        parent_provenance=parent_hashes["provenance.toml"],
        parent_bnd=parent_hashes["network.bnd"],
        parent_cfg=parent_hashes["baseline.cfg"],
    )
    return text[:cut] + "\n" + block


#: provenance.toml hash key for each file whose bytes change.
_HASH_KEYS = {
    "network.bnd": "network_bnd",
    "topology.tsv": "topology",
    "executable_modules_network.mmd": "executable_modules_network",
    "README.md": "readme",
    "executable_model_manifest.tsv": "executable_model_manifest",
    LOCAL_ADJUDICATIONS: "topology_increment_adjudications",
}


def build_increment(
    root: Path,
    change_ids: tuple[str, ...] = ALL_CHANGES,
    model_version: str = MODEL_VERSION,
) -> dict[str, bytes]:
    """Every file of the increment, as bytes, keyed by path relative to its dir.

    Pure: reads v0.5.1 and the shared adjudications, writes nothing.
    """
    changes = _changes(change_ids)
    parent = root / PARENT_DIR
    files: dict[str, bytes] = {
        str(path.relative_to(parent)): path.read_bytes()
        for path in sorted(parent.rglob("*"))
        if path.is_file()
    }
    parent_hashes = {name: _sha256_bytes(data) for name, data in files.items()}

    files["network.bnd"] = _repair_bnd(
        files["network.bnd"].decode("utf-8"), changes
    ).encode("utf-8")
    files[LOCAL_ADJUDICATIONS] = _tsv_bytes(
        local_adjudication_rows(
            _read_tsv(parent / LOCAL_ADJUDICATIONS), change_ids, model_version
        ),
        ADJUDICATION_COLUMNS,
        "\n",
    )

    # Reconcile against what is about to be written, so the retirements are
    # derived by the repository's own parity code, not asserted.
    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp)
        (scratch / "network.bnd").write_bytes(files["network.bnd"])
        (scratch / LOCAL_ADJUDICATIONS).write_bytes(files[LOCAL_ADJUDICATIONS])
        topology = reconcile(
            parse_bnd_rules(scratch / "network.bnd"),
            _read_tsv(parent / "edge_evidence.tsv"),
            adjudications_for_increment(root, scratch / LOCAL_ADJUDICATIONS),
        )
    files["topology.tsv"] = _tsv_bytes(topology, TOPOLOGY_COLUMNS, "\r\n")
    files["executable_modules_network.mmd"] = _repair_mermaid(
        files["executable_modules_network.mmd"].decode("utf-8"), changes
    ).encode("utf-8")
    files["executable_model_manifest.tsv"] = _repair_manifest(
        files["executable_model_manifest.tsv"], model_version, changes
    )
    files["README.md"] = _readme(model_version, changes).encode("utf-8")

    new_hashes = {key: _sha256_bytes(files[name]) for name, key in _HASH_KEYS.items()}
    files["provenance.toml"] = _repair_provenance(
        files["provenance.toml"].decode("utf-8"),
        model_version,
        changes,
        new_hashes,
        parent_hashes,
    ).encode("utf-8")
    return files


def write_increment(
    root: Path,
    change_ids: tuple[str, ...] = ALL_CHANGES,
    model_version: str = MODEL_VERSION,
) -> Path:
    """Write the increment. Refuses to touch anything outside its own directory."""
    if model_version == PARENT_VERSION:
        raise ValueError("refusing to overwrite the parent")
    destination = root / SUPERSET_DIR / model_version
    if destination.exists():
        shutil.rmtree(destination)
    for name, data in build_increment(root, change_ids, model_version).items():
        path = destination / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return destination


def _reads(rules: dict[str, str]) -> dict[str, set[str]]:
    return {
        node: set(re.findall(r"\b\w+\b", logic)) - {"and", "or", "not", node}
        for node, logic in rules.items()
    }


def affected_nodes(rules: dict[str, str], changed: set[str]) -> set[str]:
    """The changed nodes and every transitive reader of them."""
    reads = _reads(rules)
    affected = set(changed)
    frontier = set(changed)
    while frontier:
        frontier = {n for n, r in reads.items() if r & frontier} - affected
        affected |= frontier
    return affected


def structural_identity(
    root: Path, model_version: str = MODEL_VERSION
) -> dict[str, Any]:
    """The composed-function comparison, and the blast radius, from the rules."""
    parent_free, parent_cols, states = truth_tables(root / PARENT_DIR)
    free, cols, _ = truth_tables(root / SUPERSET_DIR / model_version)
    parent_rules = parse_bnd_rules(root / PARENT_DIR / "network.bnd")
    rules = parse_bnd_rules(root / SUPERSET_DIR / model_version / "network.bnd")
    changed = sorted(n for n in rules if rules[n] != parent_rules.get(n))
    reads = _reads(rules)
    return {
        "free_variables_parent": list(parent_free),
        "free_variables": list(free),
        "enumerated_assignments": states,
        "nodes": len(rules),
        "rules_changed": changed,
        "nodes_whose_composed_function_differs": sorted(
            n for n in cols if cols[n] != parent_cols.get(n)
        ),
        "readers_of_changed_nodes": {
            node: sorted(n for n, r in reads.items() if node in r) for node in changed
        },
        "affected_nodes": sorted(affected_nodes(rules, set(changed))),
    }


