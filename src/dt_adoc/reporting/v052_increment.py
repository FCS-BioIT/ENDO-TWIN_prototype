"""v0.5.2: emit ``adoc-literature-superset-v0.5.2`` from v0.5.1, and prove what moved.

The 2026-09-28 reconciliation of the 163-paper literature re-audit found two
absorbed conjuncts that the evidence does not support as causal gates:

    C1  OUT_EPITHELIAL_RECEPTIVE   = E_RECEPTIVE_SURFACE and E_PAEP
        OUT_EPITHELIAL_RECEPTIVE   = E_RECEPTIVE_SURFACE
    C5  E_ESTROGENIC_PROLIFERATION = IN_E2 and S_FGF_MITOGENIC and not S_HAND2
        E_ESTROGENIC_PROLIFERATION = IN_E2 and S_FGF_MITOGENIC

C1 is an output-semantics correction. PAEP/glycodelin is a
secretory-differentiation readout that no primary source perturbs with an
adhesion endpoint, so it must not define the receptivity phenotype. It remains
an observable state.

C5 is a semantic correction of the model architecture, recorded as
SEMANTIC_OR_PROTOCOL. It is not an algebraic cleanup. The unsupported direct
HAND2 veto on epithelial proliferation is removed, and HAND2 now acts only
through the existing stromal relay (``S_FGF_MITOGENIC = not S_HAND2``). That
changes asynchronous transients by design.

Over the free variables, the composed function of every node is unchanged;
``structural_identity`` checks that node by node rather than inferring it.
``v052_interventions`` lists the internal clamps under which the two versions
do differ.

This follows ``dt_adoc.reporting.u5b_increment`` exactly. An audited model
version is a fixed object, so the increment is emitted as a new directory and
v0.5.1 is left as it is. ``tests/unit/test_v052_paep_hand2.py`` rebuilds the
directory in a scratch tree and requires it byte for byte.

Unlike U5b, neither changed node is a leaf, so the transient reaches
descendants. It is measured on the design frozen in
``docs/v052_paep_hand2/transient_preregistration.md``.

``build_increment`` takes the change set as a parameter only so that the
pre-registered single-change attribution arms (C1-only, C5-only) come from the
same code. Those are written into a scratch root by the transient runner and
never committed as model versions.

Changed files, each asserted file by file:

* ``network.bnd`` -- the rules.
* ``topology.tsv`` -- regenerated by ``dt_adoc.model.topology.reconcile``.
  ``LE077`` and ``LE094`` become ``retired``.
* ``topology_increment_adjudications.tsv`` -- v0.5.1's U5b rows (``LE079`` and
  ``LE080`` stay retired) plus one dated row per retired edge. These are
  version-local for U5b's reason: the shared file's hash is pinned by versions
  that still execute these edges.
* ``executable_modules_network.mmd`` -- the arrows that no longer execute.
* ``provenance.toml``, ``README.md``, ``executable_model_manifest.tsv`` --
  self-naming and the ``[increment]`` record.

Deliberately NOT changed, as in U5b:

* ``edge_evidence.tsv`` keeps ``LE077``/``LE094`` as curated history; the
  retirement lives in ``topology.tsv``.
* ``complete_edges.tsv``, ``complete_nodes.tsv`` and ``rule_variants.tsv`` state
  their content against the v0.4.0 family. Their rows say
  ``implementation_model_version = adoc-literature-superset-v0.4.0`` or
  ``variant_id = adoc_literature_superset_v040``, where both conjuncts do
  execute, so they are still true. The superset runtime applies no rule-variant
  overrides, so the catalog cannot re-impose the old rule.
* ``phenotype_contract.tsv`` and ``node_dictionary.tsv`` describe the phenotypes,
  not the rules.
"""

