def _changes(change_ids: tuple[str, ...]) -> tuple[RuleChange, ...]:
    unknown = sorted(set(change_ids) - set(CHANGES))
    if unknown or not change_ids or len(set(change_ids)) != len(change_ids):
        raise ValueError(f"change set must be distinct ids from {ALL_CHANGES}")
    return tuple(CHANGES[c] for c in ALL_CHANGES if c in change_ids)


def local_adjudication_rows(
    parent_rows: list[dict[str, str]],
    change_ids: tuple[str, ...] = ALL_CHANGES,
    model_version: str = MODEL_VERSION,
) -> list[dict[str, str]]:
    """The parent's version-local rows, unchanged, then one row per retired edge."""
    new = [
        {
            "exemption_id": f"INC-V052-{change.change_id}",
            "source_node": change.retired_source,
            "target_node": change.node,
            "category": "stale_topology_row_undocumented_migration",
            "adjudication": "retire_row_preserve_assertions",
            "rationale": _RATIONALE.format(
                edge_id=change.edge_id,
                change_id=change.change_id,
                source=change.retired_source,
                target=change.node,
                model_version=model_version,
                reason=change.reason,
            ),
            "action_required": "none",
            "dated": GENERATED_ON,
        }
        for change in _changes(change_ids)
    ]
    return [dict(row) for row in parent_rows] + new


def _repair_bnd(text: str, changes: tuple[RuleChange, ...]) -> str:
    for change in changes:
        pattern = re.compile(
            rf"(Node {change.node} \{{\n  logic = ){re.escape(change.logic_before)}(;\n\}})"
        )
        text, count = pattern.subn(rf"\g<1>{change.logic_after}\g<2>", text)
        if count != 1:
            raise ValueError(
                f"{change.node}'s parent rule not found exactly once ({count})"
            )
    return text


def _repair_mermaid(text: str, changes: tuple[RuleChange, ...]) -> str:
    for change in changes:
        if text.count(change.arrow) != 1:
            raise ValueError(f"arrow {change.arrow.strip()!r} not found exactly once")
        text = text.replace(change.arrow, "")
    return text


def _version_tag(model_version: str) -> str:
    """``adoc-literature-superset-v0.5.2`` -> ``v0.5.2`` (variants keep their suffix)."""
    prefix = "adoc-literature-superset-"
    if not model_version.startswith(prefix + "v"):
        raise ValueError(f"not a superset version: {model_version!r}")
    return model_version[len(prefix) :]


def _family_key(model_version: str) -> str:
    """``adoc-literature-superset-v0.5.2`` -> ``adoc_literature_superset_v052``."""
    tag = _version_tag(model_version).replace(".", "").replace("-", "_")
    return f"adoc_literature_superset_{tag}"


