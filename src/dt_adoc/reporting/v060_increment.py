def _rule_changes() -> tuple[RuleChange, ...]:
    return tuple(rule for marker in MARKERS for rule in marker.rules)


def _lines(text: str) -> list[str]:
    return text.splitlines(keepends=True)


def _remove_node_blocks(text: str) -> str:
    rules = parse_bnd_rules_text(text)
    for marker in MARKERS:
        if rules.get(marker.node) != marker.node:
            raise ValueError(f"{marker.node} is not a constant input node")
        readers = sorted(
            node
            for node, logic in rules.items()
            if node != marker.node and re.search(rf"\b{marker.node}\b", logic)
        )
        expected = sorted(rule.node for rule in marker.rules)
        if readers != expected:
            raise ValueError(f"{marker.node} is read by {readers}, not {expected}")
        block = re.compile(
            rf"Node {marker.node} \{{\n  logic = {marker.node};\n\}}\n\n"
        )
        text, count = block.subn("", text)
        if count != 1:
            raise ValueError(f"{marker.node}'s block not found exactly once")
    for rule in _rule_changes():
        pattern = re.compile(
            rf"(Node {rule.node} \{{\n  logic = ){re.escape(rule.logic_before)}(;\n\}})"
        )
        text, count = pattern.subn(rf"\g<1>{rule.logic_after}\g<2>", text)
        if count != 1:
            raise ValueError(f"{rule.node}'s parent rule not found exactly once")
    for node in DELETED_NODES:
        if re.search(rf"\b{node}\b", text):
            raise ValueError(f"{node} is still named in the network")
    return text


def parse_bnd_rules_text(text: str) -> dict[str, str]:
    """``{node: logic}`` from network text, through the repository's own parser."""
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "network.bnd"
        path.write_text(text, encoding="utf-8")
        return parse_bnd_rules(path)


def _remove_cfg_lines(text: str) -> str:
    """Drop every assignment to a deleted node, keeping every other byte."""
    pattern = re.compile(rf"^\s*(?:{'|'.join(DELETED_NODES)})\.\w+\s*=")
    kept = [line for line in _lines(text) if not pattern.match(line)]
    result = "".join(kept)
    for node in DELETED_NODES:
        if re.search(rf"\b{node}\b", result):
            raise ValueError(f"{node} is still named in a cfg")
    return result


def _remove_rows(name: str, data: bytes) -> bytes:
    column = _ROW_KEY_COLUMN.get(name, 0)
    lines = _lines(data.decode("utf-8"))
    kept = [lines[0]] + [
        line for line in lines[1:] if line.split("\t")[column] not in DELETED_NODES
    ]
    removed = len(lines) - len(kept)
    if removed == 0:
        raise ValueError(f"{name} names no deleted node")
    result = "".join(kept)
    for node in DELETED_NODES:
        if re.search(rf"\b{node}\b", result):
            raise ValueError(f"{node} is still named in {name}")
    return result.encode("utf-8")


def _remove_mermaid(text: str) -> str:
    kept = [
        line
        for line in _lines(text)
        if not any(re.search(rf"\b{node}\b", line) for node in DELETED_NODES)
    ]
    expected = len(DELETED_NODES) + len(_rule_changes())
    if len(_lines(text)) - len(kept) != expected:
        raise ValueError(f"expected {expected} mermaid lines naming deleted nodes")
    return "".join(kept)


def local_adjudication_rows(parent_rows: list[dict[str, str]]) -> list[dict[str, str]]:
    """The parent's version-local rows, unchanged, then one row per retired edge."""
    new = []
    for marker in MARKERS:
        for edge_id, rule in zip(marker.edge_ids, marker.rules, strict=True):
            new.append(
                {
                    "exemption_id": f"INC-V060-{edge_id}",
                    "source_node": marker.node,
                    "target_node": rule.node,
                    "category": "stale_topology_row_undocumented_migration",
                    "adjudication": "retire_row_preserve_assertions",
                    "rationale": _RATIONALE.format(
                        edge_id=edge_id,
                        source=marker.node,
                        target=rule.node,
                        model_version=MODEL_VERSION,
                        intervention_id=marker.intervention_id,
                        design=DESIGN_DOC,
                    ),
                    "action_required": "none",
                    "dated": GENERATED_ON,
                }
            )
    return [dict(row) for row in parent_rows] + new


