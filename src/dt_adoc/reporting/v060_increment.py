def _protocol_row(definition: Any) -> dict[str, Any]:
    """A v0.5.2 definition as a v0.6.0 row: markers become named interventions."""
    steps = []
    for step in definition.steps:
        named = sorted(
            MIGRATED_INTERVENTIONS[node]
            for node, value in step.input_states.items()
            if node in MIGRATED_INTERVENTIONS and value
        )
        if step.interventions:
            raise ValueError(
                f"{definition.protocol_id} already names interventions on v0.5.2"
            )
        entry: dict[str, Any] = {
            "step_id": step.step_id,
            "relative_order": step.relative_order,
            "relative_duration": step.relative_duration,
            "duration_note": step.duration_note,
            "input_states": {
                node: value
                for node, value in step.input_states.items()
                if node not in MIGRATED_INTERVENTIONS
            },
        }
        if named:
            entry["interventions"] = named
        steps.append(entry)
    parent_cfg = f"{PARENT_DIR.as_posix()}/conditions/"
    if not definition.condition_cfg.startswith(parent_cfg):
        raise ValueError(f"{definition.protocol_id} cfg is outside {parent_cfg}")
    row: dict[str, Any] = {
        "protocol_id": definition.protocol_id,
        "protocol_class": definition.protocol_class,
        "model_version": MODEL_VERSION,
        "condition_cfg": definition.condition_cfg.replace(
            parent_cfg, f"{MODEL_DIR.as_posix()}/conditions/"
        ),
        "comparator_role": definition.comparator_role,
    }
    if definition.continuation_from is not None:
        row["continuation_from"] = definition.continuation_from
    if definition.continuation is not None:
        row["continuation"] = {
            "mode": definition.continuation.mode,
            "memory_policy": definition.continuation.memory_policy,
            "memory_nodes": list(definition.continuation.memory_nodes),
            "probability_cutoff": definition.continuation.probability_cutoff,
        }
    row["steps"] = steps
    row["evidence_ids"] = list(definition.evidence_ids)
    row["notes"] = definition.notes
    return row


def build_protocols(root: Path) -> bytes:
    """``config/protocols_markerless.yaml``: every v0.5.2 protocol, migrated.

    Generated from the resolved v0.5.2 definitions, so the schedule is the
    parent's by construction rather than by transcription.
    """
    from dt_adoc.protocols.conditions import protocol_definitions

    definitions = protocol_definitions(root, model_version=PARENT_VERSION)
    payload = {
        "schema_version": "1.0",
        "generated_on": GENERATED_ON,
        "generated_by": "dt_adoc.reporting.v060_increment",
        "description": (
            "Protocol rows for superset versions whose intervention markers were "
            "removed (MARKERLESS_FROM_SUPERSET_VERSION and later). Each step names "
            "its interventions instead of setting an IN_* marker. Generated from "
            f"the {PARENT_VERSION} definitions; see {DESIGN_DOC}. "
            "config/protocols.yaml is a closed input and is not edited."
        ),
        "protocols": [_protocol_row(d) for d in definitions.values()],
    }
    return (json.dumps(payload, indent=2) + "\n").encode("utf-8")


