def _repair_provenance(
    parent_text: str,
    new_hashes: dict[str, str],
    condition_hashes: dict[str, str],
    parent_hashes: dict[str, str],
    condition_files: list[str],
    protocols_sha: str,
) -> str:
    text = parent_text
    for old, new in (
        (
            'family_id = "adoc_literature_superset_v052"',
            'family_id = "adoc_literature_superset_v060"',
        ),
        (f'model_version = "{PARENT_VERSION}"', f'model_version = "{MODEL_VERSION}"'),
        ('generated_on = "2026-09-28"', f'generated_on = "{GENERATED_ON}"'),
        (
            'generator_module = "dt_adoc.reporting.v052_increment"',
            'generator_module = "dt_adoc.reporting.v060_increment"',
        ),
    ):
        if text.count(old) != 1:
            raise ValueError(f"provenance header line not found exactly once: {old}")
        text = text.replace(old, new)
    note = re.compile(r'^generator_note = ".*"$', re.MULTILINE)
    text, count = note.subn(
        f'generator_note = "Emitted from {PARENT_VERSION} by '
        "dt_adoc.reporting.v060_increment as that version without its "
        "intervention-marker nodes. dt_adoc.model.superset_family.MODEL_VERSION "
        'still targets v0.4.0 and emits no v0.5 or v0.6 directory."',
        text,
    )
    if count != 1:
        raise ValueError("generator_note not found exactly once")
    parent_prefix = f'"{PARENT_DIR.as_posix()}/'
    if text.count(parent_prefix) != 18:
        raise ValueError("expected 18 [artifacts] paths naming the parent")
    text = text.replace(parent_prefix, f'"{MODEL_DIR.as_posix()}/')
    for key, digest in {**new_hashes, **condition_hashes}.items():
        line = re.compile(rf'^{key}_sha256 = "[0-9a-f]{{64}}"$', re.MULTILINE)
        text, count = line.subn(f'{key}_sha256 = "{digest}"', text)
        if count != 1:
            raise ValueError(f"{key}_sha256 not found exactly once")
    cut = text.index("\n[increment]\n")
    edges = [edge for marker in MARKERS for edge in marker.edge_ids]
    block = _INCREMENT_BLOCK.format(
        parent_dir=PARENT_DIR.as_posix(),
        parent_version=PARENT_VERSION,
        generated_on=GENERATED_ON,
        transformation=TRANSFORMATION,
        deleted=", ".join(f'"{n}"' for n in DELETED_NODES),
        kept=KEPT_REAGENT_INPUT,
        rule_lines="\n".join(
            f'{r.node.lower()}_logic_before = "{r.logic_before}"\n'
            f'{r.node.lower()}_logic_after = "{r.logic_after}"'
            for r in _rule_changes()
        ),
        migrated=", ".join(
            f'{node} = "{iid}"' for node, iid in MIGRATED_INTERVENTIONS.items()
        ),
        protocols=PROTOCOLS_PATH.as_posix(),
        protocols_sha=protocols_sha,
        edges=", ".join(f'"{e}"' for e in edges),
        design=DESIGN_DOC,
        changed="\n".join(
            f'  "{name}",' for name in sorted([*CHANGED_FILES, *condition_files])
        ),
        parent_provenance=parent_hashes["provenance.toml"],
        parent_bnd=parent_hashes["network.bnd"],
        parent_cfg=parent_hashes["baseline.cfg"],
    )
    return text[:cut] + "\n" + block


def build_increment(root: Path) -> dict[str, bytes]:
    """Every file of the new version, as bytes, keyed by path relative to its dir.

    Pure: reads v0.5.2 and the shared adjudications, writes nothing.
    """
    parent = root / PARENT_DIR
    files: dict[str, bytes] = {
        path.relative_to(parent).as_posix(): path.read_bytes()
        for path in sorted(parent.rglob("*"))
        if path.is_file()
    }
    parent_hashes = {name: _sha256_bytes(data) for name, data in files.items()}

    files["network.bnd"] = _remove_node_blocks(
        files["network.bnd"].decode("utf-8")
    ).encode("utf-8")
    files["baseline.cfg"] = _remove_cfg_lines(
        files["baseline.cfg"].decode("utf-8")
    ).encode("utf-8")
    conditions = sorted(name for name in files if name.startswith("conditions/"))
    for name in conditions:
        files[name] = _remove_cfg_lines(files[name].decode("utf-8")).encode("utf-8")
    for name in ROW_FILES:
        files[name] = _remove_rows(name, files[name])
    files[LOCAL_ADJUDICATIONS] = _tsv_bytes(
        local_adjudication_rows(_read_tsv(parent / LOCAL_ADJUDICATIONS)),
        ADJUDICATION_COLUMNS,
        "\n",
    )
    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp)
        (scratch / "network.bnd").write_bytes(files["network.bnd"])
        (scratch / LOCAL_ADJUDICATIONS).write_bytes(files[LOCAL_ADJUDICATIONS])
        topology = reconcile(
            parse_bnd_rules(scratch / "network.bnd"),
            _read_tsv(parent / "edge_evidence.tsv"),
            adjudications_for_increment(root, scratch / LOCAL_ADJUDICATIONS),
        )
    files["topology.tsv"] = _tsv_bytes(topology, TOPOLOGY_COLUMNS, "\r\n")
    files["executable_modules_network.mmd"] = _remove_mermaid(
        files["executable_modules_network.mmd"].decode("utf-8")
    ).encode("utf-8")
    files["executable_model_manifest.tsv"] = _repair_manifest(
        files["executable_model_manifest.tsv"]
    )
    files["README.md"] = _readme().encode("utf-8")

    new_hashes = {key: _sha256_bytes(files[name]) for name, key in _HASH_KEYS.items()}
    condition_hashes = {
        f"{Path(name).stem}_cfg": _sha256_bytes(files[name]) for name in conditions
    }
    files["provenance.toml"] = _repair_provenance(
        files["provenance.toml"].decode("utf-8"),
        new_hashes,
        condition_hashes,
        parent_hashes,
        conditions,
        # The schedule that times the migrated interventions, bound by content.
        _sha256_bytes(build_protocols(root)),
    ).encode("utf-8")
    return files


