_CLAIM = (
    "Reproduces the {parent} rule {node} = {before}, whose marker {marker} "
    "{child} deletes. Licensed by exhaustive equivalence with the {parent} row of "
    "the same intervention and by gate G8. {tail}"
)


def library_rows(root: Path) -> list[dict[str, str]]:
    """The v0.6.0 rows of ``config/intervention_library.tsv``, from the v0.5.2 rows.

    The three vetoes become ``migrated_legacy_behaviour``; XAV939 keeps its
    ``executable_legacy_behaviour`` / ``no_executable_effect`` row, on the
    ``IN_XAV939`` node v0.6.0 still has.
    """
    from dt_adoc.perturbations.engine import LIBRARY_PATH, MIGRATED_BASIS

    with (root / LIBRARY_PATH).open(encoding="utf-8", newline="") as handle:
        parent_rows = [
            row
            for row in csv.DictReader(handle, delimiter="\t")
            if row["model_version"] == PARENT_VERSION
        ]
    rules = {r.node: r for r in _rule_changes()}
    markers = {m.intervention_id: m for m in MARKERS}
    rows = []
    for row in parent_rows:
        new = dict(row, model_version=MODEL_VERSION)
        marker = markers.get(row["intervention_id"])
        if marker is None:
            if row["legacy_input_node"] != KEPT_REAGENT_INPUT:
                raise ValueError(f"unexpected v0.5.2 row {row['intervention_id']}")
            new["abstraction_sources"] = row["abstraction_sources"].replace(
                PARENT_DIR.as_posix(), MODEL_DIR.as_posix()
            )
            new["claim_boundary"] = (
                "No v0.6.0 rule reads IN_XAV939. This states that the model encodes "
                "no effect; it is not a claim that XAV939 has no biological effect."
            )
        else:
            rule = rules[row["target_node"]]
            tail = row["claim_boundary"].split(". ", 1)[1]
            new.update(
                legacy_input_node="",
                legacy_perturbation_ids="",
                mapping_basis=MIGRATED_BASIS,
                abstraction_sources=";".join(
                    [
                        f"{PARENT_DIR.as_posix()}/node_dictionary.tsv#{marker.node}",
                        (
                            f"{LIBRARY_PATH.as_posix()}#{row['intervention_id']}"
                            f"@{PARENT_VERSION}"
                        ),
                    ]
                ),
                claim_boundary=_CLAIM.format(
                    parent=PARENT_VERSION,
                    node=rule.node,
                    before=rule.logic_before,
                    marker=marker.node,
                    child=MODEL_VERSION,
                    tail=tail,
                ),
            )
        rows.append(new)
    return rows


def write_increment(root: Path) -> Path:
    """Write the version and the migrated protocol file; never touch the parent."""
    destination = root / MODEL_DIR
    if destination.resolve() == (root / PARENT_DIR).resolve():
        raise ValueError("refusing to overwrite the parent")
    files = build_increment(root)
    protocols = build_protocols(root)
    if destination.exists():
        shutil.rmtree(destination)
    for name, data in files.items():
        path = destination / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    (root / PROTOCOLS_PATH).write_bytes(protocols)
    return destination


