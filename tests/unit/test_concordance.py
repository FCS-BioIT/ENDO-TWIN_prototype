    def test_every_never_binding_edge_drawn_is_verified(self) -> None:
        """B4: the legend calls these verified over all 524,288 states.

        Both struck-through edges must correspond to inhibitions the exhaustive
        enumeration actually reports as never binding. Only one of the two was
        asserted anywhere before, so the second was published as verified while
        nothing verified it and it could drift silently on a rule change.
        """
        from dt_adoc.concordance.render import PANEL_C_EDGES, PANEL_C_NODES
        from dt_adoc.reporting.structure import load_structure

        facts = load_structure("adoc-literature-superset-v0.4.0", ROOT)
        never_binding = set(facts.never_binding_inhibitions)
        dependencies = {(source, target) for source, target, _p in facts.edges}
        drawn = [(a, b) for a, b, kind in PANEL_C_EDGES if kind == "never_binding"]
        self.assertEqual(len(drawn), 2, "expected both anti-adhesive vetoes")
