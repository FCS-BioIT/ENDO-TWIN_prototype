class GeneratorArtifactAgreement(unittest.TestCase):
    """Every derived column must still equal what its generator emits.

    `biological_unit` is written only by `table._biological_unit`, but the
    committed table is regenerated by `build-concordance`, which runs MaBoSS
    for six arms at five seeds and is far too slow for a unit suite. So the
    artifact could -- and did -- keep a superseded string after the generator
    was corrected: `docs/concordance/concordance_table.tsv` went on asserting
    the pre-annotation PAEP ceiling ("<=4 donor groups") after REL-003 and
    SOFIA-ANNO-007 tightened it to at most 3 independent units and 2 epithelial
    source groups, and nothing failed.

    This replays the generator over the committed rows instead of rerunning the
    simulation, so the agreement is checked at unit-test cost. It reads only
    curated columns, never a simulated number.
    """

    @classmethod
    def setUpClass(cls) -> None:
        cls.rows = _rows(TABLE)

    def test_biological_unit_matches_the_generator(self) -> None:
        from dt_adoc.concordance.table import _biological_unit

        self.assertTrue(self.rows, "committed concordance table is empty")
        mismatched = [
            (row["result_id"], row["biological_unit"], _biological_unit(row))
            for row in self.rows
            if row["biological_unit"] != _biological_unit(row)
        ]
        self.assertEqual(
            mismatched,
            [],
            "committed biological_unit disagrees with table._biological_unit; "
            "regenerate with `pixi run build-concordance`",
        )


class ClaimBoundary(unittest.TestCase):
    def test_no_row_claims_quantitative_agreement(self) -> None:
        """Structurally unavailable, so its count must stay zero.

        The converged horizon drives almost every readout to exactly 0 or 1, and
        the one graded endpoint is an arithmetic consequence of two hand-set
        relay probabilities. There is no validated observation model relating a
        pg/mL concentration to a trajectory frequency. A row claiming
        quantitative agreement would therefore be wrong, not merely optimistic.
        """
        classes = [row["concordance_class"] for row in _rows(TABLE)]
        self.assertEqual(classes.count("quantitative_agreement"), 0)

    def test_no_row_claims_structural_falsification(self) -> None:
        """The class must stay empty until a dynamic proof exists.

        An earlier revision promoted R43b here from an exhaustive Boolean
        enumeration showing ``OUT_STABLE_ADHESION`` is false in every assignment
        with ``IN_MIFEPRISTONE`` set. That proves a property of the target
        function, not of the simulated observable: MaBoSS is asynchronous and
        stochastic, and the same arm records 0.000050 at the declared horizon.
        Claiming zero likelihood needs a proof over the admitted rates, initial
        states and horizons, which this repository does not have.
        """
        from dt_adoc.concordance.build import STRUCTURAL_FALSIFICATION_IDS

        self.assertEqual(STRUCTURAL_FALSIFICATION_IDS, {})
        classes = [row["concordance_class"] for row in _rows(TABLE)]
        self.assertEqual(classes.count("structural_falsification"), 0)

    def test_the_declared_horizon_run_refutes_a_zero_probability_claim(self) -> None:
        """Keep the counterexample under test, not only in a comment."""
        payload = json.loads(RUN_SETTINGS.read_text(encoding="utf-8"))
        declared = next(
            arm
            for arm in payload["arms"]
            if arm["arm_id"] == "mifepristone" and arm["horizon_class"] == "declared"
        )
        self.assertGreater(declared["node_mean"]["OUT_STABLE_ADHESION"], 0.0)

    def test_the_generated_class_never_contradicts_the_curated_verdict(self) -> None:
        """The two records must not disagree silently.

        A row the analysis calls unassessable while the curated matrix calls it
        a disagreement leaves the matrix narrative counting a contradiction this
        table does not, with neither file saying so. Reclassification belongs in
        the curated file; this asserts it happened there.
        """
        from dt_adoc.concordance.build import UNASSESSABLE_RESULT_IDS

        rows = {row["result_id"]: row for row in _rows(TABLE)}
        for result_id in UNASSESSABLE_RESULT_IDS:
            self.assertEqual(
                rows[result_id]["curated_verdict"],
                "not_assessable",
                f"{result_id} is overridden here but not reclassified upstream",
            )

    def test_the_regimen_relation_is_recorded_on_both_mifepristone_rows(self) -> None:
        """Both rows must state how the simulated arm relates to the recorded one.

        This asserted "differs from the recorded one" while the protocol wiring
        bypassed the maternal mifepristone phase. The wiring is repaired, so the
        expected relation is inverted -- but the REQUIREMENT is unchanged and is
        the point of the test: neither row may go silent about the regimen. A
        row that simply stopped mentioning it would have passed the old test's
        intent while hiding exactly what it was written to surface.
        """
        rows = {row["result_id"]: row for row in _rows(TABLE)}
        for result_id in ("R43a", "R43b"):
            with self.subTest(result_id=result_id):
                fidelity = rows[result_id]["regimen_fidelity"]
                self.assertIn("matches the recorded regimen", fidelity)
                self.assertNotIn("differs from the recorded one", fidelity)

    def test_circular_rows_are_labelled_circular(self) -> None:
        """A row whose evidence built or filtered the model must say so.

        `config/observation_model_map.tsv` makes OM-001 the feasibility gate on
        the retained ensemble and OM-002 a reported diagnostic, so agreeing with
        either is agreement with the filter. The class name has to carry that.
        """
        for row in _rows(TABLE):
            if row["curated_verdict"] == "circular_by_construction":
                self.assertEqual(
                    row["concordance_class"], "calibration_circular_agreement"
                )

    def test_no_artifact_uses_a_forbidden_phrase(self) -> None:
        for path in (TABLE, FIGURE_DATA, MECHANISM_NODES):
            text = path.read_text(encoding="utf-8").lower()
            for phrase in FORBIDDEN_PHRASES:
                if phrase == "validated":
                    continue  # appears only in explicit negations, checked above
                self.assertNotIn(phrase, text, f"{phrase!r} in {path.name}")


class Provenance(unittest.TestCase):
    def test_the_committed_figure_was_drawn_from_the_committed_source_data(
        self,
    ) -> None:
        """A rebuild that is not followed by a re-render must fail here.

        The figure and its source data are two tracked files updated by two
        different commands, so they can disagree while every other check passes.
        They did: the protocol-lineage repair moved the mifepristone
        declared-horizon value to 0.000020 in `figure_source_data.tsv` and
        regenerated the table, and nobody re-ran `render-concordance`. The
        committed PNG went on drawing 0.000050 -- the withdrawn pre-repair
        artifact, and the exact 1/20000 coincidence that
        `docs/maboss_estimator_semantics.md` exists to dismantle -- through a
        merge and a green suite, because the provenance tests all read the
        source data rather than the picture.

        The sidecar now pins the digest of what was drawn, which makes the
        disagreement checkable without reading pixels.
        """
        metadata = json.loads(FIGURE_METADATA.read_text(encoding="utf-8"))
        self.assertIn(
            "source_data_sha256",
            metadata,
            "the figure sidecar predates the staleness guard; re-render it",
        )
        self.assertEqual(
            metadata["source_data"],
            str(FIGURE_DATA.relative_to(ROOT)),
            "the sidecar points at a different source file than the tests read",
        )
        self.assertEqual(
            metadata["source_data_sha256"],
            hashlib.sha256(FIGURE_DATA.read_bytes()).hexdigest(),
            "docs/concordance/figure_source_data.tsv has changed since the "
            "committed figure was drawn: run `pixi run render-concordance` and "
            "commit the regenerated figure and sidecar",
        )

    def test_the_figure_sidecar_records_every_condition_it_depends_on(
        self,
    ) -> None:
        """A condition added after the render must not go unrecorded.

        The same staleness showed a second way: `washout.cfg` was added by the
        protocol-lineage repair and the figure's provenance block never learned
        of it, so the sidecar described a model that no longer existed.
        """
        metadata = json.loads(FIGURE_METADATA.read_text(encoding="utf-8"))
        recorded = set(metadata["provenance"]["condition_cfg_sha256"])
        conditions = (
            ROOT
            / "models"
            / "superset"
            / metadata["provenance"]["model_version"]
            / "conditions"
        )
        on_disk = {path.name for path in conditions.glob("*.cfg")}
        self.assertEqual(
            recorded,
            on_disk,
            "the figure sidecar's condition set differs from the model's; "
            "re-render the figure",
        )
        for name, digest in metadata["provenance"]["condition_cfg_sha256"].items():
            self.assertEqual(
                digest,
                hashlib.sha256((conditions / name).read_bytes()).hexdigest(),
                f"{name} changed since the figure was drawn",
            )

    def test_every_regenerated_value_points_at_a_tracked_artifact(self) -> None:
        for row in _rows(TABLE):
            if row["simulated_value_regenerated"]:
                self.assertTrue(row["simulated_artifact"])
                self.assertTrue((ROOT / row["simulated_artifact"]).exists())

    def test_regenerated_values_match_the_run_settings(self) -> None:
        """The table may not carry a number the run artifact does not contain."""
        payload = json.loads(RUN_SETTINGS.read_text(encoding="utf-8"))
        available = {
            (arm["arm_id"], arm["horizon_class"]): arm["node_mean"]
            for arm in payload["arms"]
        }
        from dt_adoc.concordance.build import ARM_OF_RESULT

        for row in _rows(TABLE):
            regenerated = row["simulated_value_regenerated"]
            if not regenerated:
                continue
            arm = ARM_OF_RESULT[row["result_id"]]
            node = row["dt_node_or_proxy"]
            expected = available[(arm, row["horizon_class"])][node]
            self.assertAlmostEqual(float(regenerated), expected, places=6)

    def test_every_regenerated_value_carries_the_across_seed_spread(self) -> None:
        """The one recorded uncertainty diagnostic must actually be recorded.

        The across-seed spread is what `docs/maboss_estimator_semantics.md`
        section 3c names as the defensible empirical ruler here: it assumes
        nothing about the estimator's internals and it propagates through the
        multi-phase continuation. It is still only a diagnostic -- it is exactly
        zero for the near-zero arms, and five seeds bound gross instability
        rather than estimating a variance -- but it must be present, so that a
        reader is never shown a regenerated value with no spread beside it.
        """
        for row in _rows(TABLE):
            if row["simulated_value_regenerated"]:
                self.assertNotEqual(row["simulated_sd_across_seeds"], "")

    def test_no_artifact_reports_a_standard_error_for_simulated_occupancy(
        self,
    ) -> None:
        """The withdrawn binomial plug-in may not return, under any name.

        `simulated_trajectory_se` / `node_trajectory_se` recorded
        `sqrt(p(1-p)/n)` over the pooled draws. `docs/maboss_estimator_semantics.md`
        section 1 reads the estimator from pinned MaBoSS source: a node value is
        accumulated dwell TIME over `(tick x trajectories)`, so the
        per-trajectory contribution is a continuous occupancy fraction and not a
        Bernoulli indicator. Binomial variance describes a sum of indicators, so
        the plug-in was the WRONG VARIANCE FAMILY (section 3d) -- not a loose
        estimate that a caveat could rehabilitate, and not something a rename
        could fix either, which is why it is deleted rather than relabelled.

        Deleting it loses nothing: it was a deterministic function of
        `node_mean` and `trajectory_count * len(seeds)`, and the record still
        carries all three, so the old number remains recomputable by anyone who
        wants to compute an inapplicable quantity.

        This guard is deliberately about the SIMULATOR. The companion test below
        asserts that experimental counts keep their Wilson intervals.
        """
        banned = ("trajectory_se", "binomial error", "nominal binomial")

        header = _rows(TABLE)[0].keys()
        for column in header:
            for token in banned:
                self.assertNotIn(
                    token,
                    column,
                    f"the concordance table reintroduced {column!r}; a "
                    "standard error of a MaBoSS occupancy is the wrong "
                    "variance family, see docs/maboss_estimator_semantics.md",
                )

        settings = json.loads(RUN_SETTINGS.read_text(encoding="utf-8"))
        for arm in settings["arms"]:
            for field in arm:
                # A suffix test, not a substring one: `node_by_seed` is the
                # per-seed record the audit trail depends on and must survive.
                self.assertFalse(
                    field.endswith("_se") or "trajectory_se" in field,
                    f"run_settings arm {arm['arm_id']} reintroduced {field!r}",
                )
            self.assertIn("node_sd", arm, "the across-seed spread must remain")
            self.assertIn("node_by_seed", arm, "the per-seed record must remain")

        for row in _rows(FIGURE_DATA):
            if not row["quantity"].startswith("simulated_"):
                continue
            for token in banned:
                self.assertNotIn(
                    token,
                    row["n"].lower(),
                    f"figure source data for {row['arm']} still reports a "
                    "binomial error for a simulated occupancy",
                )
            self.assertEqual(
                (row["ci_low"], row["ci_high"]),
                ("", ""),
                "a simulated occupancy may never carry an interval",
            )

    def test_the_withdrawal_is_scoped_to_the_simulator_not_to_counting(
        self,
    ) -> None:
        """Wilson intervals on OBSERVED embryo counts are correct and must stay.

        A blanket ban would be wrong: the prohibition is about MaBoSS's
        time-averaged occupancy, never about counting embryos. R41b's 9/19
        attached blastocysts is a binomial proportion in the ordinary sense and
        `docs/maboss_estimator_semantics.md` section 3d says so explicitly. If
        this test ever fails because the observed intervals were stripped too,
        the cleanup over-reached.
        """
        observed = [
            row
            for row in _rows(FIGURE_DATA)
            if row["quantity"] == "observed_proportion" and row["panel"] == "A"
        ]
        self.assertTrue(observed, "panel A lost its observed attachment counts")
        for row in observed:
            self.assertNotEqual(
                row["ci_low"], "", f"{row['arm']} lost its Wilson interval"
            )
            self.assertNotEqual(row["ci_high"], "", f"{row['arm']} lost its CI")
            self.assertRegex(row["n"], r"^\d+/\d+$")

    def test_the_generating_source_does_not_recompute_the_plug_in(self) -> None:
        """A guard on the code, because an artifact guard alone is not enough.

        The columns could be dropped while the module kept computing the
        quantity, and the next maintainer would find it sitting there looking
        usable. The formula itself must be gone from the concordance simulation
        path.
        """
        source = (ROOT / "src" / "dt_adoc" / "concordance" / "simulate.py").read_text(
            encoding="utf-8"
        )
        body = source.split('"""', 2)[2] if source.count('"""') >= 2 else source
        for token in ("sqrt(", "node_trajectory_se"):
            self.assertNotIn(
                token,
                body,
                "the withdrawn binomial plug-in is computable again in "
                "concordance/simulate.py",
            )

    def test_no_resolvability_claim_is_made_about_the_declared_value(self) -> None:
        """Neither a sigma nor a resolution limit may be asserted.

        Two candidate criteria were tried and both are refuted by the run
        artifact: a binomial standard error assumes independent trajectory
        draws, and a `1/trajectory_count` resolution assumes the marginal is a
        count, but `OUT_STROMAL_DECIDUALIZED = 0.04054164922510266` is neither.
        With no validated characterisation of the estimator, the analysis makes
        no claim about whether 0.000050 against 0.000000 is resolvable, and
        R43a's classification rests on horizon instability alone. It rested on the
        regimen mismatch until that wiring defect was repaired.
        """
        narrative = (ROOT / "docs" / "concordance_analysis.md").read_text(
            encoding="utf-8"
        )
        forbidden = (
            "sigma from zero",
            "nominal error",
            "run's resolution",
            "resolution limit",
            "applicable uncertainty",
            "consistent with independent",
            "within error",
            "is one trajectory",
            "exactly 1/20 000",
        )
        for phrase in forbidden:
            self.assertNotIn(phrase, narrative, f"{phrase!r} still concludes")
        self.assertIn("no validated characterisation", narrative)

        rows = {row["result_id"]: row for row in _rows(TABLE)}
        # R43a's regimen now matches; it stays unassessable on the HORIZON
        # instead, and the field must say which reason applies so the repaired
        # regimen is not read as having made the row comparable.
        self.assertIn("matches the recorded regimen", rows["R43a"]["regimen_fidelity"])
        self.assertIn("NOT assessable", rows["R43a"]["regimen_fidelity"])

    def test_no_row_describes_a_value_as_a_count_of_trajectories(self) -> None:
        """The contradiction the narrative guard above could not see.

        The R43a record simultaneously called 0.000050 "one trajectory in 20000"
        and declared that these values are not trajectory counts and that the
        estimator's sampling semantics are uncharacterised. The count phrasing
        asserts exactly the interpretation the same record says is unestablished,
        and it lived in the curated matrix, which the narrative guard does not
        read, so it survived every revision of the analysis prose.

        Checked across the curated matrix and the generated table, since the
        generator copies the note into the latter.
        """
        forbidden = tuple(
            # Assembled rather than written out, so this guard does not itself
            # contain the phrasing it bans and trip on its own source.
            f"{article} {noun} in 20{sep}000"
            for article in ("one", "a single")
            for noun in ("trajectory", "path")
            for sep in ("", ",")
        ) + ("is one trajectory", "one trajectory out of")
        sources = {
            "concordance_table.tsv": _rows(TABLE),
            "results_reproducibility_matrix.tsv": _rows(
                ROOT / "docs" / "results_reproducibility_matrix.tsv"
            ),
        }
        for name, rows_ in sources.items():
            for row in rows_:
                blob = " ".join(value or "" for value in row.values())
                for phrase in forbidden:
                    with self.subTest(source=name, result_id=row.get("result_id")):
                        self.assertNotIn(
                            phrase,
                            blob,
                            f"{phrase!r} asserts a trajectory-count reading of an "
                            "estimator this repository records as uncharacterised",
                        )

    def test_r43b_agrees_with_the_demonstrated_converged_comparison(self) -> None:
        """The generated table and the narrative must not contradict each other.

        An earlier revision of `build._regimen_mismatch` said R43b's magnitude
        comparison was NOT robust to the regimen mismatch, while
        `docs/concordance_analysis.md` and
        `tests/integration/test_concordance_runtime.py` both say the converged
        endpoint is unchanged when the maternal mifepristone phase is inserted --
        so direction AND magnitude both survive. The canonical table carried the
        opposite scientific interpretation of its own measured comparison.

        R43b is read at the converged horizon; R43a is the declared-horizon
        transient and is the row the mismatch actually invalidates.
        """
        rows = {row["result_id"]: row for row in _rows(TABLE)}
        fidelity = rows["R43b"]["regimen_fidelity"]
        self.assertIn("BOTH the direction and the magnitude failure survive", fidelity)
        # Bounded, not absolute: an earlier revision asserted exact invariance
        # from a single-seed 2000-trajectory counterfactual, which `AGENTS.md`
        # forbids -- fixed seeds give reproducibility, not Monte Carlo stability.
        self.assertIn("No claim of exact invariance beyond those runs", fidelity)
        self.assertIn("reproducibility, not Monte Carlo stability", fidelity)
        # And the row it does invalidate is named, so the two are not confused.
        self.assertIn("R43a", fidelity)
        self.assertNotIn("the magnitude comparison and the declared-horizon", fidelity)

    def test_no_r43b_surface_claims_exact_finite_horizon_invariance(self) -> None:
        """B16: the bound adopted for `regimen_fidelity` must hold everywhere.

        The guard above bounds ONE field. An earlier revision bounded exactly
        that field and left the stronger claim standing in the places a reader
        actually meets it -- the curated row note (which the generator copies
        into the canonical table) and `docs/concordance_analysis.md`, which
        together said the converged support "is {0}", that the observed residual
        "cannot be produced" there, that the endpoint is "lineage-invariant", and
        that inserting the maternal phase "cannot" change R43b's value.

        Those are claims of exact FINITE-horizon invariance, and this repository
        disproves them on its own artifacts: `docs/concordance/run_settings.json`
        records `OUT_STABLE_ADHESION = 0.000050` for the SAME arm on the SAME
        lineage at the declared horizon, so a finite-horizon probability here is
        not identically zero and not a fixed-point consequence.

        What IS proved is asymptotic, and is allowed to be stated as such: the
        network is a DAG over its 19 free variables, and exhaustive enumeration
        over all 524,288 assignments puts `OUT_STABLE_ADHESION` at 0 in the fixed
        point in every one of the 262,144 with `IN_MIFEPRISTONE` set. This test
        holds the line between the two: the asymptotic statement may be absolute,
        the finite-horizon one must name its runs.

        WHAT THIS CHECK ACTUALLY IS, stated plainly because an earlier revision
        of this docstring overstated it. It is a list of literal phrasings, scoped
        to the sentence they appear in: each is permitted only where the same
        sentence also says `asymptotic`, and is a defect anywhere else. The
        sentence scoping is what makes it better than the flat ban tried first --
        that version flagged the narrative's proved claim about the t -> infinity
        limit, which is exactly the sentence the analysis is entitled to state
        absolutely -- but scoping a phrase list does not turn it into an
        enforcement of the methodological boundary, and this docstring previously
        claimed it did.

        WHAT IT DOES NOT COVER, so no later round mistakes it for complete:

        * Synonyms. Any wording not in `banned` passes. A review round found
          exactly that -- the method name and docstring asserting the endpoint
          "does not depend on the upstream lineage", inside a file this guard
          already scanned. That phrasing is now listed, which closes the instance
          and not the class.
        * Other fields. It reads the `note` of two rows and three whole files. It
          never reads `regimen_fidelity` -- that field has its own guard, the test
          directly above -- nor any other column.
        * Whether a claim is true. It matches text, not evidence.

        So this guard catches recurrences of phrasings already found. It does not
        remove the need to re-check new surfaces by reading, and a later round
        should not treat a green run here as having done that.
        """
        banned = (
            # Split so that grepping the repository for a phrasing does not hit
            # this list itself. NOT a claim that the file is free of them -- the
            # docstring above quotes several verbatim in describing what was
            # withdrawn, so this module must never be added to the scanned
            # surfaces without an exemption for its own prose.
            "support here is {" + "0}",
            "support on this arm is {" + "0}",
            "cannot be " + "produced",
            "lineage-" + "invariant",
            "not regimen-" + "sensitive",
            "regimen-" + "insensitive",
            "cannot change R43" + "b",
            # Found in the runtime module docstring after three rounds had
            # bounded the prose surfaces: the same claim, one level out.
            "provably does not depend" + " on",
            "converged invariance being" + " shown",
            "cannot depend on what happened" + " earlier",
            # The method name and docstring of the lineage test, which survived
            # the class rename: a name is a surface too.
            "does not depend on the upstream" + " lineage",
        )
        # Whitespace-normalised: the narrative is hard-wrapped markdown, so a
        # phrase that spans a line break is present to a reader and absent to a
        # naive substring search -- which would make this guard silently weaker
        # on exactly the sentences it exists to hold.
        narrative = " ".join(
            (ROOT / "docs" / "concordance_analysis.md")
            .read_text(encoding="utf-8")
            .split()
        )
        curated = {
            row["result_id"]: row
            for row in _rows(ROOT / "docs" / "results_reproducibility_matrix.tsv")
        }
        generated = {row["result_id"]: row for row in _rows(TABLE)}

        # EVERY surface that states the claim, not the prose ones only. Five
        # review rounds each found this same defect class on a surface the
        # previous round's guard did not scan -- curated note, then narrative,
        # then the runtime test's class docstring, then its module docstring.
        # Bounding them one at a time is what produced that cycle, so the guard
        # enumerates the code surfaces too: the runtime module is the artifact
        # all three prose surfaces CITE, so an absolute claim surviving there is
        # the one a reader who follows the citation actually meets.
        code_surfaces = {
            "test_concordance_runtime.py": ROOT
            / "tests"
            / "integration"
            / "test_concordance_runtime.py",
            "concordance/build.py": ROOT
            / "src"
            / "dt_adoc"
            / "concordance"
            / "build.py",
        }
        surfaces = {
            "concordance_analysis.md": narrative,
            "results_reproducibility_matrix.tsv:R43b": curated["R43b"]["note"],
            "concordance_table.tsv:R43b": generated["R43b"]["note"],
        }
        for name, path in code_surfaces.items():
            # Underscores folded to spaces: in a code surface the IDENTIFIERS are
            # claim-bearing too, and a review round found the retracted absolute
            # surviving in a method name after the enclosing class had been
            # renamed. Without this fold the name spells the banned phrase with
            # `_` separators and the scan slides straight past it.
            surfaces[name] = " ".join(
                path.read_text(encoding="utf-8").replace("_", " ").split()
            )
        import re

        for name, text in surfaces.items():
            # Sentence-scoped, because the permission is sentence-scoped. Split
            # on sentence-enders followed by a space, which is what survives the
            # whitespace normalisation above for prose, docstrings and comments
            # alike.
            sentences = re.split(r"(?<=[.;:!?])\s+", text)
            for phrase in banned:
                for sentence in sentences:
                    if phrase not in sentence:
                        continue
                    with self.subTest(surface=name, phrase=phrase):
                        self.assertIn(
                            "asymptotic",
                            sentence.lower(),
                            f"{phrase!r} states an absolute in a sentence that "
                            "does not scope it to the asymptotic fixed point, so "
                            "it reads as exact FINITE-horizon invariance -- which "
                            "run_settings.json refutes on this same arm and "
                            f"lineage at the declared horizon. Sentence: "
                            f"{sentence!r}",
                        )

        # And the distinction is positively present, not merely un-negated: a
        # surface that deleted the overclaim without replacing it with the
        # proved/measured split would pass the bans above and say nothing.
        for name in (
            "results_reproducibility_matrix.tsv:R43b",
            "concordance_table.tsv:R43b",
        ):
            note = surfaces[name]
            with self.subTest(surface=name):
                self.assertIn("ASYMPTOTIC", note)
                self.assertIn("FINITE", note)
                self.assertIn("0.000050 at the declared horizon", note)
                self.assertIn("reproducibility, not Monte Carlo stability", note)
        self.assertIn("asymptotic", narrative)
        self.assertIn("reproducibility, not Monte Carlo stability", narrative)

        # The generator copies the curated note verbatim; if that ever stops
        # being true the two surfaces could diverge and only one be guarded.
        self.assertEqual(curated["R43b"]["note"], generated["R43b"]["note"])

