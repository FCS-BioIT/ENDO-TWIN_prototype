"""Guards on the concordance analysis.

The generated artifacts are as capable of drifting into an overclaim as prose
is, so the claims that matter are asserted here rather than promised in the
narrative. Three groups:

* **claim boundary** -- the analysis may never report quantitative agreement,
  may never call calibration agreement validation, and may never compare a
  concentration numerically to a Boolean probability.
* **provenance** -- every simulated number the figure draws must exist in a
  tracked artifact, and the figure may not draw a quantity its source data does
  not contain.
* **mechanism** -- the derived structural facts must stay true of the committed
  network, so a rule change that dissolves an alias class or activates a
  never-binding inhibition fails here rather than silently changing the figure's
  meaning.

These tests read the committed artifacts. They do not run MaBoSS: a unit suite
that simulated six arms at five seeds would be too slow to run often, and the
artifacts are the thing under review.
"""

from __future__ import annotations

import csv
import hashlib
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

CONCORDANCE_DIR = ROOT / "docs" / "concordance"
TABLE = CONCORDANCE_DIR / "concordance_table.tsv"
RUN_SETTINGS = CONCORDANCE_DIR / "run_settings.json"
FIGURE_DATA = CONCORDANCE_DIR / "figure_source_data.tsv"
MECHANISM_NODES = CONCORDANCE_DIR / "mechanism_nodes.tsv"
SCRNA_AUDIT = CONCORDANCE_DIR / "scrna_object_audit.json"
FIGURE = ROOT / "docs" / "assets" / "adoc_concordance_v0.4.0.png"
FIGURE_METADATA = FIGURE.with_name(FIGURE.stem + "_metadata.json")

#: Phrases that would overstate what a MaBoSS trajectory frequency supports.
FORBIDDEN_PHRASES = (
    "quantitatively reproduced",
    "validated",
    "clinical",
    "causal",
    "proves",
    "confirms the mechanism",
)


def _rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


