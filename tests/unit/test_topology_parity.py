"""Parity between the executable network and its curated relation provenance.

Parity is now produced by the generator rather than merely checked afterwards:
``write_family`` reconciles before it writes, so an unadjudicated mismatch aborts
generation with nothing written. These tests assert the invariant holds in the
committed artifacts, that the reconciler actually refuses drift rather than passing
by luck, and that an exemption cannot outlive the mismatch it was written for.

The original defect was invisible because every validator read the relation table
and none parsed the network. Every test here starts from ``network.bnd``.
"""

from __future__ import annotations

import csv
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from dt_adoc.model.topology import (
    ACTIVE_STATUSES,
    CATEGORY_TO_STATUS,
    TOPOLOGY_COLUMNS,
    TopologyParityError,
    coverage_counts,
    derive_dependencies,
    load_adjudications,
    parse_bnd_rules,
    reconcile,
)

SUPERSET = ROOT / "models/superset/adoc-literature-superset-v0.3.0"
ADJUDICATIONS = ROOT / "config/topology_parity_exemptions.tsv"

#: Parent models are declared immutable and are not regenerated by this increment.
#: Their drift is pinned exactly so it can shrink but never grow, and so the numbers
#: cannot be quietly restated. See docs/topology_parity_correction.md.
PINNED_PARENT_DRIFT = {
    "models/baseline/adoc-core-v0.1.0": (12, 14),
    "models/extended/adoc-literature-v0.2.0": (2, 0),
}


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


class SupersetParityTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.rules = parse_bnd_rules(SUPERSET / "network.bnd")
        cls.derived = derive_dependencies(cls.rules)
        cls.curated = read_rows(SUPERSET / "edge_evidence.tsv")
        cls.topology = read_rows(SUPERSET / "topology.tsv")
        cls.adjudications = load_adjudications(ADJUDICATIONS)

    def test_topology_columns_match_the_declared_schema(self) -> None:
        self.assertEqual(list(self.topology[0]), list(TOPOLOGY_COLUMNS))

    def test_active_relations_are_exactly_the_executing_dependencies(self) -> None:
        active = {
            (row["source"], row["target"])
            for row in self.topology
            if row["provenance_status"] in ACTIVE_STATUSES
        }
        self.assertEqual(sorted(set(self.derived) - active), [])
        self.assertEqual(sorted(active - set(self.derived)), [])

    def test_committed_topology_matches_a_fresh_reconciliation(self) -> None:
        fresh = reconcile(self.rules, self.curated, self.adjudications)
        self.assertEqual(fresh, [dict(row) for row in self.topology])

    def test_coverage_is_reported_as_declared_over_active(self) -> None:
        counts = coverage_counts(self.topology)
        self.assertEqual(counts["declared_edge_count"], 92)
        self.assertEqual(counts["unprovenanced_edge_count"], 3)
        self.assertEqual(counts["logical_aggregate_edge_count"], 1)
        self.assertEqual(counts["retired_edge_count"], 1)
        self.assertEqual(counts["active_edge_count"], 96)
        self.assertEqual(counts["relation_count"], 97)
        self.assertEqual(
            counts["active_edge_count"],
            counts["declared_edge_count"]
            + counts["unprovenanced_edge_count"]
            + counts["logical_aggregate_edge_count"],
        )

    def test_unprovenanced_relations_carry_no_edge_id(self) -> None:
        """The whole point: a dependency without curated support must not acquire
        an identifier that would let it be counted as covered."""
        for row in self.topology:
            if row["provenance_status"] in {"unprovenanced", "logical_aggregate"}:
                self.assertEqual(row["edge_id"], "", row)
                self.assertTrue(row["exemption_id"].strip(), row)

    def test_unprovenanced_relations_have_no_evidence_row_at_all(self) -> None:
        curated_pairs = {(row["source"], row["target"]) for row in self.curated}
        for row in self.topology:
            if row["provenance_status"] in {"unprovenanced", "logical_aggregate"}:
                self.assertNotIn((row["source"], row["target"]), curated_pairs)

    def test_declared_relations_carry_an_edge_id_and_no_exemption(self) -> None:
        for row in self.topology:
            if row["provenance_status"] == "declared":
                self.assertTrue(row["edge_id"].strip(), row)
                self.assertEqual(row["exemption_id"], "", row)

    def test_retired_le081_keeps_its_evidence_and_all_eight_assertions(self) -> None:
        retired = [r for r in self.topology if r["provenance_status"] == "retired"]
        self.assertEqual([r["edge_id"] for r in retired], ["LE081"])
        self.assertEqual(retired[0]["exemption_id"], "PAR-005")
        self.assertNotIn(
            (retired[0]["source"], retired[0]["target"]), set(self.derived)
        )
        row = next(r for r in self.curated if r["edge_id"] == "LE081")
        self.assertEqual(row["evidence_id"], "LIT-LIF-001")
        assertions = read_rows(SUPERSET / "edge_evidence_assertions.tsv")
        self.assertEqual(len([a for a in assertions if a["edge_id"] == "LE081"]), 8)

    def test_derived_sign_agrees_with_every_curated_sign(self) -> None:
        """Sign is machine-derived by a real parse, so curated polarity is
        cross-checked rather than trusted. A token-local heuristic would get the
        parenthesised negation in X_MECHANICAL_PERMISSIVE_ECM wrong."""
        by_pair = {(r["source"], r["target"]): r for r in self.curated}
        for pair, sign in self.derived.items():
            curated = by_pair.get(pair)
            if curated is not None:
                self.assertEqual(sign, curated["sign"], pair)

    def test_parenthesised_negation_derives_as_inhibition(self) -> None:
        for source in (
            "IN_ER_STRESS_EXCESS",
            "IN_HIGH_ECM_STIFFNESS",
            "X_MECHANICAL_STRESS_RELAY",
        ):
            self.assertEqual(
                self.derived[(source, "X_MECHANICAL_PERMISSIVE_ECM")], "inhibition"
            )

    def test_no_dependency_has_ambiguous_polarity(self) -> None:
        ambiguous = sorted(p for p, s in self.derived.items() if s == "ambiguous")
        self.assertEqual(ambiguous, [])


class AdjudicationRegistryTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.adjudications = load_adjudications(ADJUDICATIONS)
        cls.topology = read_rows(SUPERSET / "topology.tsv")

    def test_every_adjudication_is_realised_in_the_topology(self) -> None:
        """An exemption that stops corresponding to a real mismatch must fail, so a
        temporary tolerance cannot silently outlive its repair."""
        realised = {
            (row["source"], row["target"]): row["exemption_id"]
            for row in self.topology
            if row["exemption_id"].strip()
        }
        self.assertEqual(sorted(realised), sorted(self.adjudications))
        for pair, row in self.adjudications.items():
            self.assertEqual(realised[pair], row["exemption_id"])

    def test_every_adjudication_carries_a_dated_signed_decision(self) -> None:
        for pair, row in self.adjudications.items():
            for field in ("category", "adjudication", "rationale", "dated"):
                self.assertTrue(row[field].strip(), f"{pair} missing {field}")
            self.assertIn(row["category"], CATEGORY_TO_STATUS, pair)


class ReconcilerRefusesDriftTest(unittest.TestCase):
    """The reconciler must actually fail on drift, not merely pass today."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.rules = parse_bnd_rules(SUPERSET / "network.bnd")
        cls.curated = read_rows(SUPERSET / "edge_evidence.tsv")
        cls.adjudications = load_adjudications(ADJUDICATIONS)

    def test_new_unadjudicated_dependency_raises(self) -> None:
        rules = dict(self.rules)
        rules["OUT_STABLE_ADHESION"] += " and E_PGR"
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(rules, self.curated, self.adjudications)
        self.assertIn("E_PGR -> OUT_STABLE_ADHESION", str(caught.exception))

    def test_removed_dependency_without_retirement_raises(self) -> None:
        rules = dict(self.rules)
        rules["E_GP130_STAT3"] = "E_GP130_STAT3"
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(rules, self.curated, self.adjudications)
        self.assertIn("do not compute", str(caught.exception))

    def test_curated_sign_contradicting_the_rule_raises(self) -> None:
        curated = [dict(row) for row in self.curated]
        flipped = next(r for r in curated if r["sign"] == "activation")
        flipped["sign"] = "inhibition"
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(self.rules, curated, self.adjudications)
        self.assertIn("but the rule uses it as", str(caught.exception))

    def test_stale_adjudication_raises(self) -> None:
        adjudications = dict(self.adjudications)
        adjudications[("IN_PROGESTIN", "E_PGR")] = {
            "exemption_id": "PAR-999",
            "source_node": "IN_PROGESTIN",
            "target_node": "E_PGR",
            "category": "executing_without_provenance",
            "adjudication": "x",
            "rationale": "x",
            "action_required": "",
            "dated": "2026-07-28",
        }
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(self.rules, self.curated, adjudications)
        self.assertIn("delete the adjudication", str(caught.exception))

    def test_retired_relation_that_starts_executing_again_raises(self) -> None:
        """Otherwise retirement becomes a way to hide a live dependency.

        LE081's relation is still curated, so restoring it to the rules makes the
        retirement obsolete rather than violated -- the reconciler says so, and
        demands the adjudication be deleted.
        """
        rules = dict(self.rules)
        rules["OUT_MATERNAL_ADHESION_COMPETENCE"] += " and E_RECEPTIVE_SURFACE"
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(rules, self.curated, self.adjudications)
        message = str(caught.exception)
        self.assertIn("both executes and is curated", message)
        self.assertIn("PAR-005", message)

    def test_retirement_cannot_shelter_an_uncurated_live_dependency(self) -> None:
        """The other direction: a retirement adjudication must never cover a
        dependency that executes without a curated row."""
        rules = dict(self.rules)
        rules["OUT_MATERNAL_ADHESION_COMPETENCE"] += " and E_RECEPTIVE_SURFACE"
        curated = [r for r in self.curated if r["edge_id"] != "LE081"]
        with self.assertRaises(TopologyParityError) as caught:
            reconcile(rules, curated, self.adjudications)
        self.assertIn("adjudicated as retired", str(caught.exception))

    def test_reconciler_never_invents_an_edge_id(self) -> None:
        table = reconcile(self.rules, self.curated, self.adjudications)
        curated_ids = {row["edge_id"] for row in self.curated}
        produced = {row["edge_id"] for row in table if row["edge_id"]}
        self.assertTrue(produced <= curated_ids)


class PinnedParentDriftTest(unittest.TestCase):
    """Parent models are immutable and unrepaired; their drift is recorded exactly."""

    def test_parent_drift_matches_the_recorded_counts(self) -> None:
        for relative, (undeclared, stale) in PINNED_PARENT_DRIFT.items():
            with self.subTest(model=relative):
                model = ROOT / relative
                deps = set(derive_dependencies(parse_bnd_rules(model / "network.bnd")))
                declared = {
                    (row["source"], row["target"])
                    for row in read_rows(model / "edge_evidence.tsv")
                }
                self.assertEqual(len(deps - declared), undeclared)
                self.assertEqual(len(declared - deps), stale)


if __name__ == "__main__":
    unittest.main()
